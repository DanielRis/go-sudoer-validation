//go:build ignore

// gendefaults converts sudo's plugins/sudoers/def_data.in into the
// Defaults table used for validation.
//
// Usage: go run internal/gen/gendefaults.go internal/gen/def_data.in > defaults_table.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

type entry struct {
	name   string
	types  []string
	values []string
}

func main() {
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	var entries []*entry
	var cur *entry
	field := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if !strings.HasPrefix(line, "\t") {
			cur = &entry{name: strings.TrimSpace(line)}
			entries = append(entries, cur)
			field = 0
			continue
		}
		field++
		line = strings.TrimSpace(line)
		switch field {
		case 1:
			cur.types = strings.Split(line, "|")
		case 2:
			// description
		case 3:
			cur.values = strings.Fields(line)
		}
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	fmt.Println("// Code generated by internal/gen/gendefaults.go from sudo's def_data.in; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package sudoers")
	fmt.Println()
	fmt.Println("var defaultsTable = []defType{")
	for _, e := range entries {
		var flags []string
		for _, t := range e.types {
			flags = append(flags, "d"+strings.TrimPrefix(t, "T_"))
		}
		fmt.Printf("\t{name: %q, typ: %s", e.name, strings.Join(flags, " | "))
		if len(e.values) > 0 {
			fmt.Printf(", values: %#v", e.values)
		}
		fmt.Println("},")
	}
	fmt.Println("}")
}
